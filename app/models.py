from typing import List, Optional, Literal, Dict
from pydantic import BaseModel, Field


class Citation(BaseModel):
    chunk_id: str = Field(description="Identifier of the source chunk, e.g. chunk_1")
    quote: str = Field(max_length=350, description="Verbatim excerpt or full sentence from the chunk")
    verified: bool = Field(default=True, description="Whether quote was verified to exist in the chunk")


class KeyDate(BaseModel):
    date: str = Field(max_length=100, description="The date or deadline mentioned in the document")
    description: str = Field(max_length=200, description="What happens or is due on this date")
    citation: Citation


class MoneyAmount(BaseModel):
    amount: str = Field(max_length=100, description="The monetary figure, currency, penalty, or fee")
    context: str = Field(max_length=200, description="What this payment, fee, or liability applies to")
    citation: Citation


class Obligation(BaseModel):
    party: str = Field(max_length=100, description="Who is responsible (e.g. Employee, Client, Receiving Party, Me)")
    duty: str = Field(max_length=300, description="Specific duty, covenant, or restriction imposed")
    citation: Citation


class RedFlag(BaseModel):
    issue: str = Field(max_length=200, description="Short free-text issue title describing the clause or risk")
    category: Optional[str] = Field(default="other", max_length=100, description="Optional risk category (or 'other')")
    severity: Literal["low", "medium", "high"] = Field(description="Risk severity level")
    risk_explanation: str = Field(max_length=500, description="Why this is disadvantageous or risky, grounded strictly in the quote")
    citation: Citation


class ActionItem(BaseModel):
    action: str = Field(max_length=250, description="Concrete affirmative action directly required by the document")
    deadline: Optional[str] = Field(default=None, max_length=150, description="Exact deadline if explicitly stated in text, otherwise null")
    assignee: Optional[str] = Field(default=None, max_length=150, description="Specific party explicitly named in text, otherwise null")
    citation: Citation


# Call A Schema: Core facts & obligations
class AnalysisPartA(BaseModel):
    summary: str = Field(max_length=700, description="Concise plain-language executive summary preserving all strict qualifiers such as 'unconditional', 'without refund', or 'at sole discretion'")
    summary_citation: Citation = Field(description="Primary supporting chunk for the summary")
    key_dates: List[KeyDate] = Field(default_factory=list, description="All key dates and deadlines")
    money_amounts: List[MoneyAmount] = Field(default_factory=list, description="All monetary amounts and fees")
    obligations: List[Obligation] = Field(default_factory=list, description="Obligations and covenants on parties")


# Call B1 Schema: Red flags & risks
class RedFlagsResponse(BaseModel):
    red_flags: List[RedFlag] = Field(min_length=1, description="List of identified red flags, aggressive terms, or legal traps")


# Call B2 Schema: Action checklist
class ActionChecklistResponse(BaseModel):
    action_checklist: List[ActionItem] = Field(min_length=1, description="Concrete prioritized action items")


# Legacy alias for backward compatibility
class AnalysisPartB(BaseModel):
    red_flags: List[RedFlag] = Field(default_factory=list)
    action_checklist: List[ActionItem] = Field(default_factory=list)


class AnalysisMetrics(BaseModel):
    latency_ms: float = Field(description="Total latency in milliseconds across generation calls")
    prompt_tokens: int = Field(default=0, description="Number of tokens in prompt evaluation")
    completion_tokens: int = Field(default=0, description="Number of tokens generated by model")
    total_tokens: int = Field(default=0, description="Sum of prompt and completion tokens")
    model_name: str = Field(description="Model used for generation")
    stage_a_latency_ms: Optional[float] = None
    stage_b_latency_ms: Optional[float] = None
    stage_b1_latency_ms: Optional[float] = None
    stage_b2_latency_ms: Optional[float] = None
    stage_b_status: Literal["success", "partial", "failed"] = Field(default="success", description="Status of Stage B execution")
    exact_citations: int = Field(default=0, description="Citations matched exactly")
    normalized_citations: int = 0
    fuzzy_repaired_citations: int = 0
    dropped_citations: int = 0
    duplicates_removed: int = 0
    headings_rejected: int = 0
    ungrounded_dates_nulled: int = 0
    dropped_audit_log: List[Dict[str, str]] = Field(default_factory=list, description="Log of dropped items: type, text, reason")


class DocumentAnalysisResponse(BaseModel):
    doc_id: str
    filename: str
    summary: str
    summary_citation: Citation
    key_dates: List[KeyDate] = Field(default_factory=list)
    money_amounts: List[MoneyAmount] = Field(default_factory=list)
    obligations: List[Obligation] = Field(default_factory=list)
    red_flags: List[RedFlag] = Field(default_factory=list)
    action_checklist: List[ActionItem] = Field(default_factory=list)
    metrics: AnalysisMetrics
    chunks_count: int


class Chunk(BaseModel):
    chunk_id: str
    doc_id: str
    index: int
    text: str
    page: Optional[int] = None
    char_start: int
    char_end: int


class ChatRequest(BaseModel):
    question: str = Field(min_length=1, description="Follow-up question about the document")


class ChatResponse(BaseModel):
    answer: str
    citations: List[Citation] = Field(default_factory=list)
    metrics: AnalysisMetrics


class HealthResponse(BaseModel):
    status: str
    offline_mode: bool
    ollama_reachable: bool
    ollama_models_found: List[str]
    target_llm_ready: bool
    target_embed_ready: bool
    chroma_status: str
    directories_ok: bool
